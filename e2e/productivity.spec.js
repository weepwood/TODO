import {chooseOption} from './select-helper.js';
import {test,expect} from '@playwright/test';
test('快速录入、智能清单、备注链接及批量规划',async({page})=>{
 const fixedClock=new Date();fixedClock.setHours(8,0,0,0);await page.clock.setFixedTime(fixedClock);
 const errors=[];page.on('pageerror',e=>errors.push(e.message));await page.goto('/');
 await page.getByRole('button',{name:'新建任务',exact:true}).click();
 await page.getByRole('textbox',{name:'快速任务名称'}).fill('高优任务 !3');
 await page.getByRole('button',{name:'创建任务',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'任务标题'})).toHaveValue('高优任务');
 await page.getByRole('textbox',{name:'任务备注'}).fill('# 计划\n- **第一步**');
 await page.getByRole('button',{name:'预览',exact:true}).click();
 await expect(page.locator('.markdown-preview strong')).toHaveText('第一步');
 await page.getByRole('button',{name:'添加链接',exact:true}).click();await page.getByRole('textbox',{name:'链接地址'}).fill('https://example.com/guide');
 await page.getByRole('textbox',{name:'链接名称'}).fill('参考文档');
 await page.getByRole('dialog',{name:'添加关联链接'}).getByRole('button',{name:'添加链接',exact:true}).click();
 await expect(page.getByRole('link',{name:'打开 参考文档'})).toHaveAttribute('href','https://example.com/guide');
 await page.getByRole('button',{name:'新建智能清单'}).click();
 await page.getByRole('textbox',{name:'智能清单名称'}).fill('高优先级');
 await chooseOption(page.getByRole('combobox',{name:'筛选优先级'}),'3');
 await expect(page.locator('.smart-preview')).toContainText('匹配 1 项');
 await page.getByRole('button',{name:'保存智能清单'}).click();
 await expect(page.locator('.task-body').filter({hasText:'高优任务'})).toBeVisible();
 await page.reload();await page.locator('.nav-row').filter({hasText:'高优先级'}).click();
 await expect(page.locator('.task-body').filter({hasText:'高优任务'})).toBeVisible();
 await page.getByRole('button',{name:'每日规划',exact:true}).click();
 await page.getByRole('button',{name:'智能安排'}).click();
 await expect(page.getByRole('dialog',{name:'智能时间安排'})).toContainText('高优任务');
 await page.getByRole('button',{name:'应用安排'}).click();
 await expect(page.locator('.timeline')).toContainText('高优任务');
 await page.screenshot({path:'test-results/v05-planner.png'});
 expect(errors).toEqual([]);
});
test('窄屏导航、任务详情和对话框无水平溢出',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/');
 await page.getByRole('button',{name:'打开导航'}).click();await expect(page.locator('.sidebar')).toBeVisible();
 await page.locator('.nav-row').filter({hasText:'收集箱'}).click();
 await page.getByRole('textbox',{name:'新任务名称'}).fill('移动端任务');await page.getByRole('button',{name:'添加',exact:true}).click();
 await expect(page.getByRole('textbox',{name:'任务标题'})).toHaveValue('移动端任务');
 expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
 await page.screenshot({path:'test-results/v05-mobile.png'});
});
