test('数字步进、精确录入、取消编辑与持久化',async({page})=>{
 await page.goto('/');await page.getByRole('textbox',{name:'新任务名称'}).fill('步进验收');await page.getByRole('button',{name:'添加',exact:true}).click();
 const input=page.getByRole('spinbutton',{name:'预计分钟',exact:true});
 await expect(input).toHaveValue('30');
 await page.getByRole('button',{name:'预计分钟增加'}).click();await expect(input).toHaveValue('31');
 await input.fill('40');await page.getByRole('button',{name:'预计分钟减少'}).click();await expect(input).toHaveValue('39');
 await input.fill('1');await input.press('Enter');
 await expect(page.getByRole('button',{name:'预计分钟减少'})).toBeDisabled();
 await input.fill('20');await input.press('Escape');await expect(input).toHaveValue('1');
 await page.reload();await page.locator('.task-body').filter({hasText:'步进验收'}).click();await expect(input).toHaveValue('1');
 await page.screenshot({path:'test-results/number-stepper.png',animations:'disabled'});
});

test('时间轴同日移动预览与实际提交一致',async({page})=>{
 const state=initialState();state.tasks=[{...newTask('拖动预览','inbox','2026-12-12'),time:'10:00',duration:60}];
 await page.addInitScript(data=>localStorage.setItem('todo-workbench-v1',JSON.stringify(data)),state);
 await page.goto('/');await page.getByRole('button',{name:'每日规划',exact:true}).click();await page.getByLabel('规划日期',{exact:true}).fill('2026-12-12');
 const handle=page.getByRole('button',{name:'移动时间 拖动预览'});await handle.scrollIntoViewIfNeeded();
 const box=await handle.boundingBox(),h=await page.locator('.time-block-body').evaluate(el=>parseFloat(el.style.getPropertyValue('--hour-size')));
 const x=box.x+box.width/2,y=box.y+box.height/2;
 await page.mouse.move(x,y);await page.mouse.down();await page.mouse.move(x,y+h/2,{steps:4});
 await expect(page.locator('.time-move-preview')).toContainText('10:30');
 await expect(page.locator('button.time-block').filter({hasText:'拖动预览'})).toHaveAttribute('aria-label',/10:00–11:00/);
 await page.screenshot({path:'test-results/timeline-preview.png',animations:'disabled'});
 await page.mouse.up();await expect(page.locator('.time-move-preview')).toHaveCount(0);
 await expect(page.locator('button.time-block').filter({hasText:'拖动预览'})).toHaveAttribute('aria-label',/10:30–11:30/);
});
