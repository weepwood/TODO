import {test,expect} from '@playwright/test';
import {initialState,newTask,dayKey,shiftDay} from '../src/domain.js';
import {chooseOption} from './select-helper.js';
test('清单默认属性持久化、显式录入覆盖及实际专注统计',async({page})=>{
 const today=dayKey(),d=initialState(),a=newTask('已有任务','work',today);
 d.tasks=[a];d.sessions=[{id:'focus-a',taskId:a.id,seconds:1800,mode:'focus',startedAt:today+'T10:00:00'}];
 await page.addInitScript(d=>{if(!localStorage.getItem('todo-workbench-v1'))localStorage.setItem('todo-workbench-v1',JSON.stringify(d))},d);
 await page.setViewportSize({width:1440,height:900});await page.goto('/');
 await page.getByRole('button',{name:'设置',exact:true}).click();
 await page.getByRole('navigation',{name:'设置分类'}).getByRole('button',{name:'任务与清单'}).click();
 await chooseOption(page.getByRole('combobox',{name:'配置清单'}),'work');
 const minutes=page.getByRole('spinbutton',{name:'默认预计分钟'});
 await minutes.fill('60');await minutes.press('Enter');
 await chooseOption(page.getByRole('combobox',{name:'默认优先级'}),'2');
 await chooseOption(page.getByRole('combobox',{name:'默认计划日期'}),'tomorrow');
 await page.keyboard.press('Escape');await page.reload();
 await page.locator('[data-view-key=work]').click();
 await page.locator('.task-body').filter({hasText:'已有任务'}).click();
 await expect(page.locator('.task-focus-summary')).toContainText('实际专注 30 分钟');
 await page.getByRole('textbox',{name:'新任务名称'}).fill('默认验收 !3');
 await page.getByRole('button',{name:'添加',exact:true}).click();
 await expect.poll(()=>page.evaluate(()=>{const t=JSON.parse(localStorage.getItem('todo-workbench-v1')).tasks.find(t=>t.title==='默认验收');return t&&[t.duration,t.priority,t.date]})).toEqual([60,3,shiftDay(today,1)]);
 await expect(page.locator('.task-focus-summary')).toContainText('实际专注 0 分钟');
});
test('批量延期预览和应用保留原相对日期、排除无计划及重复任务',async({page})=>{
 const today=dayKey(),d=initialState(),a=newTask('第一项','inbox',today),b=newTask('第二项','inbox',shiftDay(today,1)),c=newTask('无计划','inbox');
 d.tasks=[a,b,c];await page.addInitScript(d=>{if(!localStorage.getItem('todo-workbench-v1'))localStorage.setItem('todo-workbench-v1',JSON.stringify(d))},d);
 await page.setViewportSize({width:1440,height:900});await page.goto('/');await page.locator('[data-view-key=inbox]').click();
 await page.locator('.task-body').filter({hasText:'第一项'}).click();
 await page.locator('.task-body').filter({hasText:'第二项'}).click({modifiers:['ControlOrMeta']});
 await page.locator('.task-body').filter({hasText:'无计划'}).click({modifiers:['ControlOrMeta']});
 await page.getByRole('button',{name:'批量延期',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'批量延期'});
 await expect(dialog).toContainText('可延期 2 项 · 跳过 1 项');
 await dialog.getByRole('button',{name:'一周',exact:true}).click();
 await page.screenshot({path:'test-results/bulk-postpone.png',animations:'disabled'});
 await dialog.getByRole('button',{name:'应用延期'}).click();
 await expect.poll(()=>page.evaluate(()=>JSON.parse(localStorage.getItem('todo-workbench-v1')).tasks.map(t=>t.date))).toEqual([shiftDay(today,7),shiftDay(today,8),'']);
});
