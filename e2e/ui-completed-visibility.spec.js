import {test,expect} from '@playwright/test';
import {initialState,newTask,dayKey} from '../src/domain.js';
test('全局默认、清单覆盖、完成和取消完成、积分回退及刷新恢复',async({page})=>{
 const today=dayKey(),state=initialState(),done=new Date().toISOString();
 const old={...newTask('历史任务','inbox',today),status:'completed',stage:'done',completedAt:done,points:5};
 const active={...newTask('当前任务','inbox',today),points:7};
 const work={...newTask('工作历史','work',today),status:'completed',stage:'done',completedAt:done};
 const deleted={...newTask('已删除记录','inbox',today),status:'completed',stage:'done',completedAt:done,deletedAt:done};
 state.tasks=[old,active,work,deleted];
 await page.addInitScript(d=>{if(!localStorage.getItem('todo-workbench-v1'))localStorage.setItem('todo-workbench-v1',JSON.stringify(d))},state);await page.goto('/');
 const inbox=()=>page.locator('[data-view-key=inbox]').click();
 const row=title=>page.locator('.task-body').filter({hasText:title});
 await inbox();await expect(row('历史任务')).toHaveCount(0);
 await page.getByRole('button',{name:'设置',exact:true}).click();
 await page.getByRole('navigation',{name:'设置分类'}).getByRole('button',{name:'任务与清单'}).click();
 const setting=page.getByRole('switch',{name:'默认显示已完成任务'});
 await expect(setting).toHaveAttribute('aria-checked','false');await setting.click();
 await page.keyboard.press('Escape');
 await expect(row('历史任务')).toBeVisible();
 await expect(row('已删除记录')).toHaveCount(0);
 await expect(page.locator('[data-view-key=inbox] small')).toHaveText('1');
 await page.getByRole('button',{name:'完成 当前任务',exact:true}).click();
 await expect(page.getByRole('button',{name:'取消完成 当前任务',exact:true})).toBeVisible();
 await expect(page.locator('.completed-list-caption small')).toHaveText('2');
 await row('历史任务').click();await expect(page.getByRole('button',{name:'取消完成任务',exact:true})).toBeEnabled();
 await page.getByRole('button',{name:'取消完成任务',exact:true}).click();
 await expect(page.getByRole('button',{name:'完成 历史任务',exact:true})).toBeVisible();
 await expect.poll(()=>page.evaluate(id=>{const t=JSON.parse(localStorage.getItem('todo-workbench-v1')).tasks.find(t=>t.id===id);return [t.status,t.completedAt,t.points]},old.id)).toEqual(['pending',null,5]);
 await page.getByRole('button',{name:'统计',exact:true}).click();
 await expect(page.locator('.points-metrics').filter({hasText:'区间净积分'})).toContainText('+7');
 await inbox();
 const menu=page.getByRole('button',{name:'分组、排序与顺序'});
 const choose=async value=>{await menu.click();await page.getByRole('menuitem',{name:/^已完成任务/}).hover();await page.getByRole('menuitemradio',{name:value,exact:true}).click()};
 await choose('隐藏');await expect(row('当前任务')).toHaveCount(0);
 await page.locator('[data-view-key=work]').click();await expect(row('工作历史')).toBeVisible();
 await inbox();await expect(row('当前任务')).toHaveCount(0);
 await page.reload();await inbox();await expect(row('当前任务')).toHaveCount(0);
 await choose('跟随设置');await expect(row('当前任务')).toBeVisible();
 await page.getByRole('button',{name:'折叠分组 已完成'}).click();await expect(row('当前任务')).toHaveCount(0);
 await page.reload();await inbox();await expect(page.getByRole('button',{name:'展开分组 已完成'})).toBeVisible();
 await page.getByRole('button',{name:'展开分组 已完成'}).click();
 await page.screenshot({path:'test-results/completed-in-list.png',animations:'disabled'});
 await page.getByRole('button',{name:'取消完成 当前任务',exact:true}).click();await expect(page.getByRole('button',{name:'完成 当前任务',exact:true})).toBeVisible();
});

test('手机清单二级菜单独立显示已完成任务并直接取消完成',async({page})=>{
 await page.setViewportSize({width:390,height:844});
 const today=dayKey(),state=initialState();
 state.tasks=[{...newTask('手机历史','inbox',today),status:'completed',stage:'done',completedAt:new Date().toISOString()}];
 await page.addInitScript(d=>{if(!localStorage.getItem('todo-workbench-v1'))localStorage.setItem('todo-workbench-v1',JSON.stringify(d));},state);
 await page.goto('/');
 // Default today view: open the ordinary inbox through existing mobile list navigation.
 await page.getByRole('button',{name:'打开导航',exact:true}).click();
 await page.locator('[data-view-key=inbox]').click();
 const menu=page.getByRole('button',{name:'分组、排序与顺序'});
 await menu.click();await page.getByRole('menuitem',{name:/^已完成任务/}).click();
 await page.getByRole('menuitemradio',{name:'显示',exact:true}).click();
 const check=page.getByRole('button',{name:'取消完成 手机历史',exact:true});
 await expect(check).toBeVisible();expect((await check.boundingBox()).height).toBeGreaterThanOrEqual(44);
 await page.screenshot({path:'test-results/completed-mobile.png',animations:'disabled'});
 await check.click();await expect(page.getByRole('button',{name:'完成 手机历史',exact:true})).toBeVisible();
});
