import {test,expect} from '@playwright/test';
import {initialState,newTask,dayKey} from '../src/domain.js';
import {chooseOption} from './select-helper.js';
test.use({storageState:{cookies:[],origins:[]}});
test('桌面拖动手柄透明背景、编辑入口悬浮显示与分组管理',async({page})=>{
 const data=initialState();data.tasks=[{...newTask('分组验收','inbox',dayKey()),priority:2}];
 await page.addInitScript(data=>{if(!localStorage.getItem('todo-workbench-v1'))localStorage.setItem('todo-workbench-v1',JSON.stringify(data))},data);
 await page.setViewportSize({width:1440,height:900});await page.goto('/');
 await page.locator('[data-view-key=inbox]').click();
 const row=page.locator('.task-row').first(),handle=row.locator('.drag-handle');
 await row.locator('.task-body').click();
 await page.mouse.move(0,0);await expect(handle).toHaveCSS('opacity','0');
 await row.hover();await expect(handle).toHaveCSS('opacity','1');
 await handle.hover();await expect(handle).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
 const org=page.locator('[data-detail-section=organization]'),edit=org.getByRole('button',{name:'编辑 组织与状态',exact:true});
 await page.mouse.move(0,0);await expect(edit).toHaveCSS('opacity','0');
 await expect(org.locator('.detail-facts dd svg')).toHaveCount(4);
 await org.hover();await expect(edit).toHaveCSS('opacity','1');
 await page.screenshot({path:'test-results/detail-hover-icons.png',animations:'disabled'});
 await edit.click();
 await expect(org.getByRole('button',{name:'完成编辑 组织与状态'})).toHaveCSS('opacity','1');
 await org.getByRole('button',{name:'新建分组',exact:true}).click();
 let dialog=page.getByRole('dialog',{name:'新建分组',exact:true});
 await dialog.getByRole('textbox',{name:'名称'}).fill('学习计划');
 await dialog.getByRole('button',{name:'保存',exact:true}).click();
 await chooseOption(org.getByRole('combobox',{name:'分组',exact:true}),{label:'学习计划'});
 await org.getByRole('button',{name:'重命名当前分组'}).click();
 dialog=page.getByRole('dialog',{name:'编辑分组',exact:true});
 await dialog.getByRole('textbox',{name:'名称'}).fill('技术学习');
 await dialog.getByRole('button',{name:'保存',exact:true}).click();
 await org.getByRole('button',{name:'完成编辑 组织与状态'}).click();
 await expect(org).toContainText('技术学习');
 await page.reload();await page.locator('[data-view-key=inbox]').click();
 await page.locator('.task-body').filter({hasText:'分组验收'}).click();
 await expect(org).toContainText('技术学习');
 await page.setViewportSize({width:390,height:844});
 await expect(edit).toHaveCSS('opacity','1');
});
