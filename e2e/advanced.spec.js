import {chooseOption} from './select-helper.js';
import {test,expect} from '@playwright/test';
test('日期浮层、快捷录入、依赖、撤销重做与范围选择',async({page})=>{
 await page.goto('/');
 const add=async title=>{await page.getByRole('textbox',{name:'新任务名称'}).fill(title);await page.getByRole('button',{name:'添加',exact:true}).click()};
 await add('规划 今天 09:00 !2');
 await expect(page.getByRole('textbox',{name:'任务标题'})).toHaveValue('规划');
 await page.getByRole('button',{name:'计划日期',exact:true}).click();
 await expect(page.locator('.date-popover')).toBeVisible();
 await page.getByRole('button',{name:'明天',exact:true}).click();
 await expect(page.getByRole('button',{name:'计划日期',exact:true})).toHaveText(/\d{4}-\d{2}-\d{2}/);
 await chooseOption(page.getByRole('combobox',{name:'重复规则'}),'weekdays');
 await expect(page.locator('.weekdays')).toBeVisible();
 await page.getByRole('button',{name:'添加提醒'}).click();
 await expect(page.getByLabel('提醒 2')).toBeVisible();
 await page.getByRole('textbox',{name:'新建子任务'}).fill('子任务 A');
 await page.getByRole('textbox',{name:'新建子任务'}).press('Enter');
 await expect(page.locator('.relation-row').filter({hasText:'子任务 A'})).toBeVisible();
 await page.locator('.nav-row').filter({hasText:'所有任务'}).click();
 await add('前置工作');
 await add('后置工作');
 await chooseOption(page.getByRole('combobox',{name:'前置任务'}),{label:'前置工作'});
 await expect(page.getByRole('button',{name:'完成 后置工作'})).toBeDisabled();
 await page.getByRole('button',{name:'撤销',exact:true}).click();
 await expect(page.getByRole('button',{name:'完成 后置工作'})).toBeEnabled();
 await page.getByRole('button',{name:'重做',exact:true}).click();
 await expect(page.getByRole('button',{name:'完成 后置工作'})).toBeDisabled();
 await page.locator('.task-body').filter({hasText:'前置工作'}).click();
 await page.locator('.task-body').filter({hasText:'后置工作'}).click({modifiers:['Shift']});
 await expect(page.locator('.bulk-bar')).toContainText('已选 2 项');
 await page.screenshot({path:'test-results/workbench-v04-light.png'});
 await page.getByRole('button',{name:'设置',exact:true}).click();
 await page.getByRole('button',{name:'深色',exact:true}).click();
 await page.getByRole('button',{name:'关闭',exact:true}).click();
 await expect(page.locator('html')).toHaveAttribute('data-theme','dark');await page.waitForTimeout(220);await page.screenshot({path:'test-results/workbench-v04-dark.png'});
});
test('万级任务虚拟列表与搜索',async({page})=>{
 await page.goto('/');await page.getByRole('textbox',{name:'新任务名称'}).waitFor();
 await expect.poll(()=>page.evaluate(()=>localStorage.getItem('todo-workbench-v1'))).not.toBeNull();
 await page.evaluate(()=>{const key='todo-workbench-v1';const state=JSON.parse(localStorage.getItem(key));const now=new Date();const today=now.getFullYear()+'-'+String(now.getMonth()+1).padStart(2,'0')+'-'+String(now.getDate()).padStart(2,'0');state.tasks=Array.from({length:10000},(_,i)=>({id:'bench-'+i,title:'基准任务 '+i,notes:'',listId:'inbox',date:today,priority:0,repeat:'none',miss:'keep',anchor:+today.slice(-2),seriesId:null,checklist:[],status:'pending',createdAt:now.toISOString(),completedAt:null}));localStorage.setItem(key,JSON.stringify(state))});
 const start=Date.now();await page.reload();await expect(page.locator('.virtual-task-list')).toBeVisible({timeout:15000});
 const rendered=await page.locator('.task-row').count();expect(rendered).toBeLessThan(80);console.log('10,000 tasks, rendered rows:',rendered,'elapsed ms:',Date.now()-start);
 await page.getByPlaceholder('搜索所有任务').fill('基准任务 9999');await expect(page.locator('.task-body').filter({hasText:'基准任务 9999'})).toBeVisible();
});
